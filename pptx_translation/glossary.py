def translate_with_glossary(text: str) -> str:
    """
    Applies glossary substitution on exact and multi-word terms,
    sorted by descending length to match longest compound phrases first.
    """
    if not text:
        return text

    # Sort keys by length descending to match compound terms before sub-terms
    sorted_terms = sorted(MANUFACTURING_GLOSSARY.keys(), key=len, reverse=True)
    
    result = text
    for term in sorted_terms:
        if term in result:
            result = result.replace(term, MANUFACTURING_GLOSSARY[term])
            
    return result
